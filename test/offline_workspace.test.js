for (const backend of ['sqlite', 'mongodb']) test(`Offline workspace: snapshot, atomic writes, conflicts, dependencies and rollback (${backend})`, { timeout: 90000 }, async t => {
 const env = backend === 'mongodb' ? await createMongoTestEnvironment() : createTestEnvironment({ DB_TYPE: 'sqlite' });t.after(() => env.cleanup());
 const user = await env.createUserAndLogin('workspace');const headers = { Cookie: user.cookie };
 const owner = (await env.request('/api/me', { headers })).data.id;
 const post = command => env.request('/api/offline/operations', { method: 'POST', headers, body: command });
 const command = (path, method, body = {}, base = null) => ({ id: randomUUID(), owner, kind: 'workspace', aquarium: '', path, method, body, base, temporaryIds: [], createdAt: new Date().toISOString() });
 const create = command('/aquariums', 'POST', { name: 'Offline', volume_l: 100 });
 const first = await post(create);assert.equal(first.status, 200, first.text);
 assert.deepEqual((await post(create)).data, first.data);
 const id = first.data.result.id;
 const state = await env.request('/api/offline/state', { headers });assert.equal(state.status, 200, state.text);
 assert.equal(state.data.responses['/aquariums'].length, 1);
 assert.ok(state.data.versions[`/aquariums/${id}`]);
 const stock = command(`/aquariums/${id}/stock`, 'POST', { species: 'Neonsalmler', count: 10 });
 const parallel = await Promise.all([post(stock), post(stock)]);parallel.forEach(result => assert.equal(result.status, 200, result.text));
 assert.deepEqual(parallel[0].data, parallel[1].data);
 const update = command(`/aquariums/${id}`, 'PUT', { name: 'Geändert', volume_l: 100 }, state.data.versions[`/aquariums/${id}`]);
 const updated = await post(update);assert.equal(updated.status, 200, updated.text);
 const stale = await post({ ...update, id: randomUUID(), body: { name: 'Veraltet' } });assert.equal(stale.status, 409, stale.text);assert.ok(stale.data.conflict.version);
 const follow = command(`/aquariums/${id}`, 'PUT', { name: 'Noch einmal', volume_l: 100 }, 'after:' + update.id);
 assert.equal((await post(follow)).status, 200);
 const invalid = await post(command(`/aquariums/${id}/stock`, 'POST', { species: '', count: -2 }));assert.equal(invalid.status, 400, invalid.text);
 const snapshot = await env.request('/api/offline/state', { headers });assert.equal(snapshot.status, 200, snapshot.text);
 assert.equal(snapshot.data.responses[`/aquariums/${id}/stock`].length, 1);
 assert.equal((await post(command('/admin/users', 'DELETE'))).status, 400);
 assert.equal((await post({ ...create, id: randomUUID(), body: null })).status, 400);
 assert.equal((await post({ ...create, id: randomUUID(), base: 12 })).status, 400);
 assert.equal((await post({ ...create, owner: owner + 1 })).status, 403);
 assert.equal((await post({ ...create, body: { name: 'different' } })).status, 409);
 const remove = command(`/aquariums/${id}`, 'DELETE', {}, snapshot.data.versions[`DELETE /aquariums/${id}`]);
 assert.equal((await post(remove)).status, 200);
 // A deleted aquarium is not resurrected by a delayed retry of its creation.
 assert.equal((await post(create)).status, 200);
 assert.equal((await env.request('/api/aquariums', { headers })).data.length, 0);
});


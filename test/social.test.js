'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const sharp = require('sharp');
const { createTestEnvironment, createMongoTestEnvironment } = require('./helpers/env');
for (const backend of ['sqlite', 'mongodb']) {
  test(`Social: öffentlicher Feed, Bildgrenzen, Rechte, Likes, Kommentare und Backup (${backend})`, { timeout: 60000 }, async (t) => {
    const env = backend === 'mongodb' ? await createMongoTestEnvironment() : createTestEnvironment({ DB_TYPE: 'sqlite' });
    t.after(() => env.cleanup());
    const owner = await env.createUserAndLogin('social_owner', 'password123');
    const friend = await env.createUserAndLogin('social_friend', 'password123');
    const admin = await env.createUserAndLogin('social_admin', 'password123', 'admin@example.com');
    const headers = { Cookie: owner.cookie }, friendHeaders = { Cookie: friend.cookie }, adminHeaders = { Cookie: admin.cookie };
    const bytes = await sharp({ create: { width: 3200, height: 2000, channels: 3, background: '#226688' } }).png().toBuffer();
    const image = `data:image/png;base64,${bytes.toString('base64')}`;
    const create = (h = headers, caption = 'Mein Aquarium 🐠') => env.request('/api/social/posts', { method: 'POST', headers: h, body: { image, text: caption, isPublic: true } });
    assert.equal((await env.request('/api/social/posts')).status, 200);
    assert.equal((await create({})).status, 401);
    assert.equal((await env.request('/api/social/posts', { method: 'POST', headers, body: { image: 'data:image/png;base64,bm90YW5pbWFnZQ==' } })).status, 400);
    assert.equal((await env.request('/api/social/posts', { method: 'POST', headers, body: { image, text: 'x'.repeat(2201) } })).status, 400);
    assert.equal((await env.request(`/api/social/authors/${owner.id}/avatar`)).status, 404);
    const avatar = `data:image/png;base64,${(await sharp({ create: { width: 32, height: 32, channels: 3, background: '#009988' } }).png().toBuffer()).toString('base64')}`;
    assert.equal((await env.request('/api/me/avatar', { method: 'POST', headers, body: { image: avatar } })).status, 200);
    const created = await create();assert.equal(created.status, 201, created.text);
    const post = created.data.post;assert.equal(post.width, 1600);assert.equal(post.height, 1000);
    assert.equal(post.author.username, 'social_owner');assert.ok(post.author.avatarUrl);assert.equal(post.canDelete, true);
    const postUrl = `/api/social/posts/${post.id}`;
    const publicPost = await env.request(postUrl);assert.equal(publicPost.status, 200);assert.equal(publicPost.data.post.canDelete, false);
    assert.equal(publicPost.data.post.filename, undefined);assert.equal(publicPost.data.post.author.email, undefined);
    assert.equal((await env.request(`/api/social/authors/${owner.id}/avatar`)).status, 200);
    const imageRes = await fetch(`${await env.start()}${postUrl}/image`);assert.equal(imageRes.status, 200);
    const storedImage = Buffer.from(await imageRes.arrayBuffer()), metadata = await sharp(storedImage).metadata();
    assert.equal(metadata.format, 'webp');assert.equal(metadata.width, 1600);assert.equal(metadata.height, 1000);assert.equal(metadata.exif, undefined);
    assert.equal((await env.request(postUrl, { method: 'DELETE', headers: friendHeaders })).status, 403);
    assert.equal((await env.request(`${postUrl}/like`, { method: 'PUT', body: { liked: true } })).status, 401);
    const likes = await Promise.all(Array.from({ length: 6 }, () => env.request(`${postUrl}/like`, { method: 'PUT', headers: friendHeaders, body: { liked: true } })));
    assert.ok(likes.every(result => result.status === 200));assert.equal((await env.request(postUrl, { headers: friendHeaders })).data.post.likeCount, 1);
    assert.equal((await env.request(postUrl, { headers: friendHeaders })).data.post.liked, true);
    assert.equal((await env.request(`${postUrl}/like`, { method: 'PUT', headers: friendHeaders, body: { liked: false } })).data.likeCount, 0);
    await env.request(`${postUrl}/like`, { method: 'PUT', headers: friendHeaders, body: { liked: true } });
    assert.equal((await env.request(`${postUrl}/comments`, { method: 'POST', body: { text: 'Nice' } })).status, 401);
    assert.equal((await env.request(`${postUrl}/comments`, { method: 'POST', headers: friendHeaders, body: { text: '  ' } })).status, 400);
    const comment = await env.request(`${postUrl}/comments`, { method: 'POST', headers: friendHeaders, body: { text: 'Schönes Becken! <script>test</script>' } });
    assert.equal(comment.status, 201);assert.equal(comment.data.comment.author.username, 'social_friend');
    assert.equal((await env.request(`/api/social/comments/${comment.data.comment.id}`, { method: 'DELETE', headers })).status, 403);
    assert.equal((await env.request(`${postUrl}/comments`)).data.comments[0].text, 'Schönes Becken! <script>test</script>');
    const { backupService } = require('../dist/backend/src/services/backup-service');
    const db = require('../dist/backend/src/db');
    const backup = await backupService.generateBackupData({ includeFiles: true });
    assert.equal(backup.data.social_posts.length, 1);assert.equal(backup.data.social_comments.length, 1);assert.equal(backup.data.social_likes.length, 1);
    const filename = backup.data.social_posts[0].filename;
    assert.ok(backup.files[filename]);assert.equal(Buffer.from(backup.files[filename], 'base64').equals(storedImage), true);
    assert.equal((await env.request(postUrl, { method: 'DELETE', headers: adminHeaders })).status, 200);
    assert.equal((await env.request(postUrl)).status, 404);assert.equal((await env.request(`${postUrl}/image`)).status, 404);
    assert.equal(await db.social.comment(comment.data.comment.id), null);
    await backupService.restoreBackup(backup);
    assert.equal((await env.request(postUrl)).data.post.likeCount, 1);assert.equal((await env.request(`${postUrl}/comments`)).data.comments.length, 1);
    assert.equal((await env.request(`/api/social/authors/${owner.id}/avatar`)).status, 200);
    const nextPost = await create();assert.equal(nextPost.status, 201);assert.ok(nextPost.data.post.id > post.id);
    const socialImage = require('../dist/backend/src/services/image-service');assert.ok(socialImage.getImagePath(filename));
    assert.equal((await env.request(`/api/social/comments/${comment.data.comment.id}`, { method: 'DELETE', headers: friendHeaders })).status, 200);
    await db.users.delete(owner.id);
    assert.equal((await env.request(postUrl)).status, 404);assert.equal(socialImage.getImagePath(filename), null);
    assert.equal((await env.request('/api/social/posts')).data.posts.length, 0);
    const { saveSocialImage } = require('../dist/backend/src/services/social-image-service');
    await assert.rejects(saveSocialImage('data:image/png;base64,' + Buffer.alloc(5 * 1024 * 1024 + 1).toString('base64')), error => error.status === 400);
    assert.equal(db.type === 'sqlite' ? db.getSchemaVersion() : await db.getSchemaVersion(), 5);
  });
}


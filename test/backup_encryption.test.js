'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { createTestEnvironment, createMongoTestEnvironment } = require('./helpers/env');

for (const backend of ['sqlite', 'mongodb']) test(`Backup-Verschlüsselung und Passwortverwaltung (${backend})`, { timeout: 90000 }, async t => {
  const options = { DB_TYPE: backend, APP_ENCRYPTION_KEY: 'ab'.repeat(32), AI_TOKEN_ENCRYPTION_KEY: null };
  const env = backend === 'sqlite' ? createTestEnvironment(options) : await createMongoTestEnvironment(options);
  t.after(() => env.cleanup());
  const admin = await env.createUserAndLogin('backup_admin', 'password123', 'admin@example.com');
  const user = await env.createUserAndLogin('backup_user');
  const headers = { Cookie: admin.cookie };
  const db = require('../dist/backend/src/db');
  const { backupService } = require('../dist/backend/src/services/backup-service');
  const crypto = require('../dist/backend/src/services/backup-crypto');
  const password = 'Mein starkes Backup Passwort 🔐';
  const config = body => env.request('/api/admin/backups/config', { method: 'PUT', headers, body });
  const create = () => env.request('/api/admin/backups/create', { method: 'POST', headers });
  assert.equal((await create()).status, 400);
  assert.equal((await config({ enabled: true })).status, 400);
  for (const invalid of [null, 123, 'kurz', 'x'.repeat(1025)]) assert.equal((await config({ password: invalid })).status, 400);
  assert.equal((await env.request('/api/admin/backups/config', { method: 'PUT', headers: { Cookie: user.cookie }, body: { password } })).status, 403);
  const saved = await config({ password, enabled: false });
  assert.equal(saved.status, 200);
  assert.equal(saved.data.config.passwordConfigured, true);
  assert.equal(JSON.stringify(saved.data).includes(password), false);
  const raw = db.getRawDb();
  const secret = backend === 'sqlite' ? raw.prepare('SELECT value FROM app_secrets').get() : await raw.collection('app_secrets').findOne({ _id: 'backup-password' });
  assert.match(secret.value, /^app:v1:/);
  assert.equal(secret.value.includes(password), false);
  assert.equal(fs.readFileSync(backupService.configFile, 'utf8').includes(password), false);
  assert.equal((await config({ password: '' })).status, 200);
  assert.equal(await crypto.readBackupPassword(raw), password);
  const first = await create();
  assert.equal(first.status, 200);
  assert.match(first.data.filename, /\.json\.gz\.enc$/);
  const archive = backupService.getBackupBuffer(first.data.filename);
  assert.equal(crypto.isEncryptedBackup(archive), true);
  assert.equal(archive.includes(Buffer.from('backup_admin')), false);
  assert.throws(() => zlib.gunzipSync(archive));
  const plain = await crypto.decryptBackup(archive, password);
  const payload = JSON.parse(zlib.gunzipSync(plain));
  assert.equal(payload.data.users.some(u => u.id === admin.id), true);
  assert.equal(payload.data.app_secrets, undefined);
  const dl = await env.request(`/api/admin/backups/${first.data.filename}/download`, { headers });
  assert.match(dl.headers.get('content-type'), /application\/octet-stream/);
  assert.equal((await config({ password: 'Anderes sicheres Passwort' })).status, 200);
  assert.deepEqual(await crypto.decryptBackup(archive), plain, 'Lokales Archiv bleibt nach Passwortwechsel lesbar');
  const rewritten = crypto.rewriteLocalBackup(archive, plain);
  assert.notDeepEqual(rewritten, archive);
  assert.deepEqual(await crypto.decryptBackup(rewritten, password), plain, 'Bildbereinigung erhält das alte Passwort');
  const second = await create();
  const newArchive = backupService.getBackupBuffer(second.data.filename);
  await assert.rejects(crypto.decryptBackup(newArchive, password), /nicht entschlüsselt/);
  const bad = Buffer.from(archive);bad[bad.length - 20] ^= 1;
  for (const [input, suppliedPassword] of [[archive, 'Falsches Passwort'], [bad, password]]) {
    const result = await env.request('/api/admin/backups/restore-upload', { method: 'POST', headers, body: { backupBase64: input.toString('base64'), password: suppliedPassword } });
    assert.equal(result.status, 400);
    assert.ok(await db.users.findById(admin.id));
  }
  process.env.APP_ENCRYPTION_KEY = 'cd'.repeat(32);
  assert.deepEqual(await crypto.decryptBackup(archive, password), plain, 'Passwort entschlüsselt unabhängig vom App-Schlüssel');
  await assert.rejects(crypto.decryptBackup(archive), /nicht entschlüsselt/);
  process.env.APP_ENCRYPTION_KEY = 'ab'.repeat(32);
  const restore = await env.request('/api/admin/backups/restore-upload', { method: 'POST', headers, body: { backupBase64: archive.toString('base64'), password } });
  assert.equal(restore.status, 200);
  assert.equal(await crypto.readBackupPassword(raw), 'Anderes sicheres Passwort', 'Restore überschreibt kein aktuelles Geheimnis');
  await backupService.restoreBackup(payload); // Legacy object import remains supported.
});

test('App-Schlüssel übernimmt alte Datei und Umgebungsvariable ohne Rotation', async t => {
  const env = createTestEnvironment({ APP_ENCRYPTION_KEY: null, AI_TOKEN_ENCRYPTION_KEY: null });
  t.after(() => env.cleanup());
  await env.start();
  const crypto = require('../dist/backend/src/services/app-crypto');
  const modern = path.join(env.getDataDir(), 'app-encryption.key');
  const legacy = path.join(env.getDataDir(), 'ai-token-encryption.key');
  fs.renameSync(modern, legacy);
  const original = fs.readFileSync(legacy, 'utf8').trim();
  assert.equal(crypto.encryptionKey(false).toString('hex'), original);
  assert.equal(fs.readFileSync(modern, 'utf8').trim(), original);
  process.env.AI_TOKEN_ENCRYPTION_KEY = 'ef'.repeat(32);
  assert.equal(crypto.encryptionKey(false).toString('hex'), 'ef'.repeat(32));
  process.env.APP_ENCRYPTION_KEY = 'ab'.repeat(32);
  assert.equal(crypto.encryptionKey(false).toString('hex'), 'ab'.repeat(32));
});

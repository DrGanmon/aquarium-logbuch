'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { createTestEnvironment, createMongoTestEnvironment } = require('./helpers/env');
for (const type of ['sqlite', 'mongodb']) {
  test(`Pflanzen im Aquarium: Bestand, Rechte, Backup und Löschung (${type})`, async t => {
    const env = type === 'mongodb' ? await createMongoTestEnvironment() : createTestEnvironment({ DB_TYPE: 'sqlite' });
    t.after(() => env.cleanup());
    const owner = await env.createUserAndLogin(`plantowner${type}`);
    const reader = await env.createUserAndLogin(`plantreader${type}`);
    const outsider = await env.createUserAndLogin(`plantother${type}`);
    const headers = { Cookie: owner.cookie };
    const created = await env.request('/api/aquariums', { method: 'POST', headers, body: { name: 'Plant tank', water_type: 'fresh', volume_l: 100 } });
    assert.equal(created.status, 200);
    const id = created.data.id, base = `/api/aquariums/${id}/plants`, plant = 'anubias-barteri-nana';
    const set = (count, cookie = owner.cookie, plantId = plant) => env.request(`${base}/${plantId}`, { method: 'PUT', headers: { Cookie: cookie }, body: { count } });
    assert.equal((await env.request(base)).status, 401);
    assert.equal((await set(3)).status, 200);
    assert.equal((await set(5)).status, 200);
    const listed = await env.request(base, { headers });
    assert.equal(listed.data.length, 1);assert.equal(listed.data[0].count, 5);assert.equal(listed.data[0].name, 'Zwerg-Speerblatt');
    const english = await env.request(base, { headers: { ...headers, 'X-Language': 'en' } });
    assert.equal(english.data[0].name, 'Dwarf Anubias');
    for (const count of [0, -1, 1.5, 10001, null, true, '3']) assert.equal((await set(count)).status, 400);
    assert.equal((await set(1, owner.cookie, 'unknown')).status, 400);
    assert.equal((await set(1, owner.cookie, 'syringodium-filiforme')).status, 400);
    assert.equal((await set(1, outsider.cookie)).status, 404);
    assert.equal((await env.request(base, { headers: { Cookie: outsider.cookie } })).status, 404);
    const share = await env.request(`/api/aquariums/${id}/shares`, { method: 'POST', headers, body: { usernameOrEmail: reader.username, role: 'view' } });
    assert.equal(share.status, 200);
    assert.equal((await env.request('/api/shares/accept', { method: 'POST', headers: { Cookie: reader.cookie }, body: { aquarium_id: id } })).status, 200);
    assert.equal((await env.request(base, { headers: { Cookie: reader.cookie } })).status, 200);
    assert.equal((await set(2, reader.cookie)).status, 403);
    assert.equal((await env.request(`${base}/${plant}`, { method: 'DELETE', headers: { Cookie: reader.cookie } })).status, 403);
    const db = require('../dist/backend/src/db');
    const readerRecord = await db.users.findByUsername(reader.username);
    await db.shares.upsert(id, readerRecord.id, 'write', 'accepted');
    assert.equal((await set(2, reader.cookie)).status, 200);
    const exported = await db.exportAllData();
    assert.equal(exported.aquarium_plants.length, 1);
    const { backupService } = require('../dist/backend/src/services/backup-service');
    const normalized = backupService.migrateBackupData({ data: exported }).data;
    assert.equal(normalized.aquarium_plants[0].count, 2);
    await db.importAllData(normalized);
    assert.equal((await db.plants.listForAquarium(id))[0].count, 2);
    await db.plants.delete(id, plant);
    assert.deepEqual(await db.plants.listForAquarium(id), []);
    await db.plants.set(id, plant, 4);
    await db.aquariums.delete(id);
    assert.deepEqual(await db.plants.listForAquarium(id), []);
    assert.deepEqual(backupService.migrateBackupData({ data: { users: [], aquariums: [] } }).data.aquarium_plants, []);
  });
}

'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { createTestEnvironment, createMongoTestEnvironment } = require('./helpers/env');

for (const backend of ['sqlite', 'mongodb']) test(`Testentwürfe: Geräte, Offline-Konflikte, atomarer Abschluss und Wiederholungen (${backend})`, { timeout: 120000 }, async t => {
  const env = backend === 'mongodb' ? await createMongoTestEnvironment() : createTestEnvironment();
  t.after(() => env.cleanup());
  const user = await env.createUserAndLogin('draft_user');
  const headers = { Cookie: user.cookie };
  const owner = (await env.request('/api/me', { headers })).data.id;
  const aquarium = (await env.request('/api/aquariums', { method: 'POST', headers, body: { name: 'Messbecken', volume_l: 100 } })).data.id;
  const path = `/aquariums/${aquarium}/measurement-draft`;
  const cfg = (await env.request('/api/config', { headers })).data;
  const suite = cfg.suites.find(suite => suite.tests.some(test => test.key === 'ph'));
  const body = { draftId: randomUUID(), when: '2026-10-18T12:00', timeZoneOffset: -120, note: 'Handy', values: { ph: '7,2' }, suite: suite.id, selected: [suite.id + ':ph'], timers: { ph: Date.now() + 60000 } };
  const command = (method, body, base, suffix = '') => ({ id: randomUUID(), owner, kind: 'workspace', aquarium: String(aquarium), path: path + suffix, method, body, base, temporaryIds: [], createdAt: new Date().toISOString() });
  const post = body => env.request('/api/offline/operations', { method: 'POST', headers, body });
  const initial = (await env.request('/api/offline/state', { headers })).data;
  assert.equal(initial.responses[path], null);
  assert.equal(initial.versions[path], 'missing');
  const create = command('PUT', body, 'missing');
  const first = await post(create);assert.equal(first.status, 200, first.text);
  assert.deepEqual((await post(create)).data, first.data);
  assert.deepEqual((await env.request('/api' + path, { headers })).data, body);
  const state = (await env.request('/api/offline/state', { headers })).data;
  assert.deepEqual(state.responses[path], body);
  const phone = command('PUT', { ...body, values: { ph: '7,4' } }, state.versions[path]);
  assert.equal((await post(phone)).status, 200);
  const tablet = command('PUT', { ...body, note: 'Tablet' }, state.versions[path]);
  const conflict = await post(tablet);assert.equal(conflict.status, 409, conflict.text);
  assert.equal(conflict.data.conflict.current.data.values.ph, '7,4');
  // Explicit conflict resolution preserves the operation id; rejected commands have no receipt.
  const rebased = { ...tablet, base: conflict.data.conflict.version };
  const resolved = await post(rebased);assert.equal(resolved.status, 200, resolved.text);
  const finalBody = { draftId: body.draftId, measured_at: new Date().toISOString(), values: { ph: 7.2 }, selectedTests: body.selected, note: body.note };
  const complete = command('POST', finalBody, resolved.data.version, '/complete');
  const invalid = await post({ ...complete, id: randomUUID(), body: { ...finalBody, values: { ph: -1 } } });
  assert.equal(invalid.status, 400, invalid.text);
  assert.ok((await env.request('/api' + path, { headers })).data, 'Validation rollback preserves draft');
  const completed = await Promise.all([post(complete), post(complete)]);
  completed.forEach(response => assert.equal(response.status, 200, response.text));
  assert.deepEqual(completed[0].data, completed[1].data);
  assert.equal((await env.request('/api' + path, { headers })).data, null);
  assert.equal((await env.request(`/api/aquariums/${aquarium}/measurements?all=true`, { headers })).data.length, 1);
  assert.equal((await post({ ...complete, id: randomUUID() })).status, 409, 'Another device cannot complete a stale draft');
  assert.equal((await post({ ...create, id: randomUUID() })).status, 409, 'Tombstone prevents an old initial draft from reappearing');
  const closedState = (await env.request('/api/offline/state', { headers })).data;
  assert.notEqual(closedState.versions[path], 'missing');
  // Backups retain tombstones and receipts too.
  const db = require('../dist/backend/src/db');
  const backup = await db.exportAllData();assert.equal(backup.measurement_drafts.length, 1);
  await db.importAllData(backup);
  assert.deepEqual((await post(complete)).data, completed[0].data);
  const directBody = { ...body, draftId: randomUUID(), operation_id: randomUUID(), base: closedState.versions[path] };
  const direct = await env.request('/api' + path, { method: 'PUT', headers, body: directBody });
  assert.equal(direct.status, 200, direct.text);
  assert.deepEqual((await env.request('/api' + path, { method: 'PUT', headers, body: directBody })).data, direct.data);
  const bad = await post(command('PUT', { ...body, selected: ['unknown:ph'] }, direct.data.version));
  assert.equal(bad.status, 400, bad.text);
  const removed = await env.request('/api' + path, { method: 'DELETE', headers, body: { operation_id: randomUUID(), base: direct.data.version } });
  assert.equal(removed.status, 200, removed.text);
  // Offline-created aquariums retain their drafts through temporary-ID remapping.
  const { applyLocalOperation, remapSnapshot, queryWorkspace } = require('../dist/backend/src/shared/offline-workspace-model');
  const local = JSON.parse(JSON.stringify(initial));
  const createLocal = { ...command('POST', { name: 'Offline-Becken', volume_l: 80 }, null), path: '/aquariums', temporaryIds: [-55] };
  applyLocalOperation(local, createLocal);
  applyLocalOperation(local, { ...command('PUT', body, 'missing'), path: '/aquariums/-55/measurement-draft' });
  const mapped = remapSnapshot(local, { '-55': 99 });
  assert.equal(queryWorkspace(mapped, '/aquariums/99/measurement-draft').values.ph, '7,2');
  applyLocalOperation(mapped, { ...command('POST', finalBody, 'some-version', '/complete'), path: '/aquariums/99/measurement-draft/complete', temporaryIds: [-66] });
  assert.equal(queryWorkspace(mapped, '/aquariums/99/measurement-draft'), null);
  assert.equal(mapped.responses['/aquariums/99/measurements?all=true'].length, 1);
  const other = await env.createUserAndLogin('draft_other');
  const otherHeaders = { Cookie: other.cookie };
  assert.equal((await env.request('/api' + path, { headers: otherHeaders })).status, 404);
  const share = role => env.request(`/api/aquariums/${aquarium}/shares`, { method: 'POST', headers, body: { usernameOrEmail: 'draft_other', role } });
  assert.equal((await share('write')).status, 200);
  assert.equal((await env.request('/api/shares/accept', { method: 'POST', headers: otherHeaders, body: { aquarium_id: aquarium } })).status, 200);
  const otherOwner = (await env.request('/api/me', { headers: otherHeaders })).data.id;
  const otherCommand = { ...create, id: randomUUID(), owner: otherOwner };
  assert.equal((await env.request('/api/offline/operations', { method: 'POST', headers: otherHeaders, body: otherCommand })).status, 200);
  assert.equal((await env.request('/api' + path, { headers })).data, null, 'Shared aquarium drafts are private to each account');
  assert.equal((await share('view')).status, 200);
  assert.equal((await env.request('/api/offline/operations', { method: 'POST', headers: otherHeaders, body: otherCommand })).status, 403, 'Receipt replay checks revoked write access');
  assert.equal((await env.request('/api' + path, { headers: otherHeaders })).status, 403);
  const viewState = (await env.request('/api/offline/state', { headers: otherHeaders })).data;
  assert.equal(Object.hasOwn(viewState.responses, path), false);
});

for (const backend of ['sqlite', 'mongodb']) test(`Werteweiser Geräteabgleich: Ergänzen, Gleichheit, Offline-Folgen, gezielte Entscheidung und Abschluss (${backend})`, { timeout: 120000 }, async t => {
  const env = backend === 'mongodb' ? await createMongoTestEnvironment() : createTestEnvironment();t.after(() => env.cleanup());
  const user = await env.createUserAndLogin('draft_merge');const headers = { Cookie: user.cookie };
  const owner = (await env.request('/api/me', { headers })).data.id;
  const aquarium = (await env.request('/api/aquariums', { method: 'POST', headers, body: { name: 'Parallelmessung', volume_l: 100 } })).data.id;
  const path = `/aquariums/${aquarium}/measurement-draft`, cfg = (await env.request('/api/config', { headers })).data;
  const suite = cfg.suites.find(suite => ['ph', 'no3', 'kh'].every(key => suite.tests.some(test => test.key === key)));
  const base = { draftId: randomUUID(), when: '2026-10-18T12:00', timeZoneOffset: -120, note: '', suite: suite.id, selected: ['ph', 'no3', 'kh'].map(key => suite.id + ':' + key), values: {}, timers: {} };
  const clone = value => JSON.parse(JSON.stringify(value));
  const command = (body, version, observed = base) => ({ id: randomUUID(), owner, kind: 'workspace', aquarium: String(aquarium), path, method: 'PUT', body, base: version, draftBase: clone(observed), temporaryIds: [], createdAt: new Date().toISOString() });
  const post = command => env.request('/api/offline/operations', { method: 'POST', headers, body: command });
  const initial = await post({ ...command(base, 'missing'), draftBase: null });assert.equal(initial.status, 200, initial.text);
  const phoneBody = { ...base, note: 'Phone', values: { ph: '7,2' } };
  const phone = command(phoneBody, initial.data.version);
  assert.equal((await post(phone)).status, 200);
  const tabletBody = { ...base, values: { no3: '10' } };
  const tablet = command(tabletBody, initial.data.version);
  const merged = await post(tablet);assert.equal(merged.status, 200, merged.text);
  assert.deepEqual(merged.data.result.draft.values, { ph: '7,2', no3: '10' });
  assert.equal(merged.data.result.draft.note, 'Phone');
  assert.deepEqual((await post(tablet)).data, merged.data, 'Lost responses are acknowledged with the original merged draft');
  const equal = await post(command({ ...base, values: { ph: '7.20', no3: '10,0' } }, initial.data.version));
  assert.equal(equal.status, 200, equal.text);assert.equal(equal.data.version, merged.data.version, 'Equal values cause no new revision');
  const follow = command({ ...tabletBody, values: { no3: '12' } }, 'after:' + tablet.id, tabletBody);
  const followed = await post(follow);assert.equal(followed.status, 200, followed.text);
  assert.deepEqual(followed.data.result.draft.values, { ph: '7,2', no3: '12' }, 'Queued steps do not remove unseen additions');
  const observed = followed.data.result.draft;
  const a = command({ ...observed, values: { ...observed.values, ph: '7,4' } }, followed.data.version, observed);
  assert.equal((await post(a)).status, 200);
  const b = command({ ...observed, values: { ...observed.values, ph: '7,6', kh: '4' } }, followed.data.version, observed);
  const conflict = await post(b);assert.equal(conflict.status, 409, conflict.text);
  assert.deepEqual(conflict.data.conflict.draftMerge.fields, ['values.ph']);
  assert.equal(conflict.data.conflict.draftMerge.merged.values.kh, '4');
  const resolution = { ...conflict.data.conflict.draftMerge.merged, values: { ...conflict.data.conflict.draftMerge.merged.values, ph: '7,6' } };
  const resolved = await post({ ...b, body: resolution, base: conflict.data.conflict.version, draftBase: conflict.data.conflict.current.data });
  assert.equal(resolved.status, 200, resolved.text);
  assert.deepEqual(resolved.data.result.draft.values, { ph: '7,6', no3: '12', kh: '4' });
  // A completion queued before seeing the merged response must include the other device's additions.
  const pending = command({ ...resolution, values: { ph: '7,6', no3: '12' } }, 'after:' + b.id, { ...resolution, values: { ph: '7,6', no3: '12' } });
  const pendingResult = await post(pending);assert.equal(pendingResult.status, 200, pendingResult.text);
  const complete = { ...command({}, 'after:' + pending.id), method: 'POST', path: path + '/complete', body: { draftId: base.draftId, values: { ph: 7.6, no3: 12 }, selectedTests: base.selected, measured_at: new Date().toISOString(), note: 'Phone' } };
  const saved = await post(complete);assert.equal(saved.status, 200, saved.text);
  const rows = (await env.request(`/api/aquariums/${aquarium}/measurements?all=true`, { headers })).data;
  assert.equal(rows.length, 1);assert.deepEqual(rows[0].values, { ph: 7.6, no3: 12, kh: 4 });
  assert.equal((await post({ ...b, id: randomUUID() })).status, 409, 'Closed sessions remain protected from merge resurrection');
});
